    def _components_ready(self, *attrs) -> bool:
        """
        Return True if all named attributes are truthy and valid.

        BUG-048 FIX: Enhanced validation to check for deleted Qt objects
        and catch RuntimeErrors from sip wrappers pointing to deleted C++ objects.

        Note: This checks actual instance attributes, NOT the lifecycle registry.
        The registry tracks components for cleanup, but components may exist
        before being registered or may not be registered at all.
        """
        for name in attrs:
            obj = getattr(self, name, None)
            if not obj:
                return False

            # BUG-048 FIX: Check if Qt object has been deleted
            try:
                if sip_isdeleted(obj):
                    print(f"[SARTRACKER] BUG-048: Component '{name}' has been deleted")
                    return False
            except (TypeError, AttributeError):
                # Not a Qt object or sip not available - just check truthiness
                pass
            except Exception as e:
                # Any other error suggests invalid state
                print(f"[SARTRACKER] BUG-048: Error checking component '{name}': {e}")
                return False

        return True

    def _enter_safe_mode(self, reason: str):
        """Disable operational actions after fatal import failures."""
        self._safe_mode_active = True
        self._safe_mode_reason = reason
        keep_enabled = {
            getattr(self, "diagnostics_action", None),
            getattr(self, "smoketest_action", None)
        }
        for action in self.actions:
            if not action or action in keep_enabled:
                continue
            try:
                action.setEnabled(False)
                action.setToolTip("Disabled due to critical import failure. Use Diagnostics for details.")
            except Exception:
                pass
        print(f"[SARTRACKER] Safe mode enabled: {reason}")

    def _safe_mode_block(self, action_label: str, *, allow_diagnostics: bool = False) -> bool:
        """
        Return True if action should be blocked due to safe mode (import failure).
        """
        if not getattr(self, "_safe_mode_active", False):
            return False
        if allow_diagnostics:
            return False
        reason = self._safe_mode_reason or "Plugin failed to load due to critical import errors."
        self._notify(
            "error",
            "SAR Tracker Safe Mode",
            f"{action_label} is unavailable: {reason}",
            duration=6
        )
        return True

