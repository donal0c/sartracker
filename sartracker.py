    def _get_available_provider_names(self) -> List[str]:
        """
        Get list of available provider display names.

        Phase 0: Startup resilience - shows which providers are available
        after graceful degradation (e.g., traccar_http may be missing if
        SSL/requests failed to load).

        Returns:
            List of provider display names, or empty list if registry unavailable.
        """
        try:
            if provider_registry:
                return [p.display_name for p in provider_registry.list_providers()]
        except Exception:
            pass
        return []

    def _get_mission_start_iso(self) -> Optional[str]:
        """
        Get mission start time as ISO8601 string for breadcrumb filtering.

        Returns the mission start time if a mission is active, or None if no
        mission is running (in which case provider will use default time window).

        Phase 1: SAR-an8 - Default breadcrumbs to mission start time.

        Returns:
            ISO8601 timestamp string or None if no active mission.
        """
        if not self.mission_controller:
            return None

        try:
            status = self.mission_controller.status_snapshot()
            # Only return start time if mission is active (not IDLE)
            if status.get('state') in ('active', 'paused'):
                return status.get('started_at')
        except Exception:
            pass

        return None

    def get_plugin_status(self, debug_hook=None) -> dict:
        """
        Get current plugin status for diagnostics.

        This is a lightweight read-only API for diagnostic tools
        to inspect plugin state without tight coupling to internal components.

        Returns:
            dict: Plugin status with keys:
                - mission_active: bool (True if mission is running)
                - mission_name: str or None (name of current mission)
                - mission_paused: bool (True if mission is paused)
                - data_source: str or None (e.g., "CSV: tracking.csv", "HTTP: Traccar")
                - provider_type: str or None (e.g., "csv", "http_traccar")
                - devices_count: int (number of tracked devices, cached)
                - last_refresh: str or None (ISO timestamp of last refresh)
                - active_tasks_count: int (number of active background tasks)

        Qt5/Qt6 Compatible: Pure Python data structures, no Qt types.

        Issue #4 Fix: Replaces widget tree scanning pattern with explicit API contract.
        Issue #1 Fix: Returns cached device count populated by background refresh tasks.
                      Never performs network I/O on UI thread.
        Phase 0 Enhancement: Added active_tasks_count for health monitoring.
        """
        status = {
            'mission_active': False,
            'mission_name': None,
            'mission_paused': False,
            'mission_elapsed_seconds': 0.0,
            'mission_active_seconds': 0.0,
            'data_source': None,
            'provider_type': None,
            'devices_count': 0,
            'last_refresh': None,
            'last_refresh_duration_ms': self._last_refresh_duration_ms,
            'active_tasks_count': 0,  # Phase 0: Task manager health metric
            # NEW: Tool registry status (Issue #2 fix)
            'tool_registry_loaded': False,
            'drawing_tools_available': False,
            'charset_guard': get_charset_guard_status(),
            # Vendor diagnostics
            'vendor': dict(_vendor_info) if _vendor_info else {},
            # Phase 0: Available providers for startup resilience diagnostics
            'available_providers': self._get_available_provider_names(),
        }

        try:
            # Safely read SAR panel state
            if self.mission_controller:
                snapshot = self.mission_controller.status_snapshot()
                state_value = snapshot.get('state')
                status['mission_active'] = state_value in ('active', 'paused')
                status['mission_paused'] = state_value == 'paused'
                status['mission_name'] = snapshot.get('mission_name')
                status['mission_elapsed_seconds'] = snapshot.get('elapsed_seconds', 0.0)
                status['mission_active_seconds'] = snapshot.get('active_seconds', 0.0)
            elif self.sar_panel:
                status['mission_active'] = getattr(self.sar_panel, 'mission_active', False)
                status['mission_paused'] = getattr(self.sar_panel, 'is_paused', False)
                if hasattr(self.sar_panel, 'mission_name_input'):
                    mission_name = self.sar_panel.mission_name_input.text().strip()
                    status['mission_name'] = mission_name if mission_name else None

            # Safely read provider state
            if self.provider:
                status['provider_type'] = self.provider_name

                # Get data source display string
                if self.provider_name == 'csv' and self.provider_config:
                    csv_path = self.provider_config.get('csv_path', '')
                    if csv_path:
                        status['data_source'] = f"CSV: {os.path.basename(csv_path)}"
                elif self.provider_name == 'http_traccar':
                    status['data_source'] = "HTTP: Traccar Server"
                elif self.provider_name == 'traccar_http':
                    base_url = (self.provider_config or {}).get('base_url')
                    status['data_source'] = f"HTTP: {base_url}" if base_url else "HTTP: Traccar Server"
                else:
                    status['data_source'] = self.provider_name

                # ============================================================
                # ISSUE #1 FIX: Use cached device count instead of querying provider
                # Cache is updated by background refresh tasks, never blocks UI
                # ============================================================
                status['devices_count'] = self._cached_device_count
                status['last_refresh'] = self._last_refresh_time
                status['last_refresh_duration_ms'] = self._last_refresh_duration_ms

                # Provider-specific diagnostics
                if hasattr(self.provider, 'get_cache_stats'):
                    try:
                        status['provider_cache_stats'] = self.provider.get_cache_stats()
                    except Exception as cache_stats_err:
                        print(f"[SARTRACKER] Warning: Error reading provider cache stats: {cache_stats_err}")

            # Read tool registry status (Issue #2 fix)
            status['tool_registry_loaded'] = self.tool_registry is not None
            if self.tool_registry:
                # Count how many tools are registered
                try:
                    # Check if registry has a method to get registered tool count
                    if hasattr(self.tool_registry, 'get_registered_tools'):
                        registered_tools = self.tool_registry.get_registered_tools()
                        status['drawing_tools_available'] = len(registered_tools) > 0
                    else:
                        # Fallback: assume tools are available if registry exists
                        status['drawing_tools_available'] = True
                except Exception as tool_error:
                    print(f"[SARTRACKER] Warning: Error reading tool registry status: {tool_error}")

            # Read task manager status (Phase 0: Health monitoring)
            # See AI_CODE_REFERENCE.md – Pattern 6 (TaskManager)
            if self.task_manager:
                try:
                    status['active_tasks_count'] = self.task_manager.get_active_count()
                except Exception as task_error:
                    print(f"[SARTRACKER] Warning: Error reading task manager status: {task_error}")
                    status['active_tasks_count'] = 0

            # ============================================================
            # PHASE 3: Read provider controller status
            # ============================================================
            if self.provider_controller:
                try:
                    controller_status = self.provider_controller.status_snapshot()
                    # Merge controller status into plugin status
                    status['provider_controller_state'] = controller_status.get('state', 'unknown')
                    status['provider_poll_active'] = controller_status.get('poll_active', False)
                    status['provider_poll_interval'] = controller_status.get('poll_interval', None)
                    status['provider_base_url'] = controller_status.get('provider_base_url')
                    status['provider_last_error'] = controller_status.get('last_error')
                    status['provider_status_message'] = controller_status.get('message')
                    status['provider_refresh_duration_ms'] = controller_status.get('last_refresh_duration_ms', self._last_refresh_duration_ms)
                except Exception as controller_error:
                    print(f"[SARTRACKER] Warning: Error reading provider controller status: {controller_error}")
            # ============================================================

        except Exception as e:
            # Defensive: Don't let diagnostics query crash plugin
            # See AI_CODE_REFERENCE.md – Pattern 9 (Defensive Guards)
            print(f"[SARTRACKER] Warning: Error reading plugin status: {e}")

        if debug_hook:
            try:
                debug_hook(status)
            except Exception as exc:
                self._log_exception("get_plugin_status.debug_hook", exc)

        return status
