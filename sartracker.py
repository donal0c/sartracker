    def run(self):
        """
        Toggle SAR Tracker panel visibility.

        Guards against initialization failure (Issue #3 fix):
        If imports failed during initGui(), self.sar_panel will be None.
        Show user-friendly error instead of crashing with AttributeError.
        """
        if self._safe_mode_block("SAR Tracker panel"):
            return
        # CRITICAL GUARD: Check if panel exists (Issue #3 fix)
        # Panel may be None if imports failed during initialization
        if not self.sar_panel:
            # Show persistent error message with actionable guidance
            error(
                self.iface.messageBar(),
                "SAR Tracker - Not Initialized",
                "Plugin failed to load due to import errors. Click 'Diagnostics' in the SAR Tracker menu for details and troubleshooting guidance.",
                duration=0  # Persistent - stays until user dismisses
            )

            # Auto-open diagnostics dialog for immediate remediation
            try:
                self._show_diagnostics()
            except Exception as e:
                # If diagnostics also fails, log but don't crash
                print(f"[SARTRACKER] Could not open diagnostics: {e}")

            return  # Early exit - don't attempt to access panel

        # Safe to proceed - panel exists and is valid
        if self.sar_panel.isVisible():
            self.sar_panel.hide()
        else:
            self.sar_panel.show()

    def _on_mission_state_changed(self, state, context):
        """Handle mission state transitions from MissionController."""
        # Guard against signals firing during plugin unload
        if self._is_unloading or self._app_is_quitting:
            return

        mission_name = context.get('mission_name') or "Mission"
        prev_state = self._last_mission_state
        self._last_mission_state = state

        if state == MissionState.ACTIVE:
            if prev_state == MissionState.PAUSED:
                message = "Mission resumed"
                self._handle_mission_resume_storage(mission_name)
            else:
                message = f"Mission '{mission_name}' started"
                # MEMORY STABILITY: Clear stale caches before new mission
                self._clear_provider_caches()
                self._prepare_new_mission_storage(mission_name)
                self._metadata_collected = False
                has_coords = bool(self._mission_coordinators_cache or (self.layer_manager and self.layer_manager.get_mission_coordinators()))
                if not has_coords:
                    self._collect_mission_metadata(mode="start", allow_resume_time=False)
            success(self.iface.messageBar(), "SAR Tracker", message, duration=3)
            self._refresh_mission_logs_window()
            if self.sar_panel:
                # Hide finalize button during active mission
                self.sar_panel.set_finalize_button_visible(visible=False)
        elif state == MissionState.PAUSED:
            warning(self.iface.messageBar(), "SAR Tracker", "Mission paused", duration=2)
            self._update_mission_storage_status(active=False)
            if self.sar_panel:
                self.sar_panel.set_finalize_button_visible(visible=False)
        elif state == MissionState.FINISHED:
            final_elapsed = context.get('final_elapsed_seconds')
            if final_elapsed:
                hours, remainder = divmod(int(final_elapsed), 3600)
                minutes, seconds = divmod(remainder, 60)
                summary = f"{hours:02d}:{minutes:02d}:{seconds:02d}"
                success(
                    self.iface.messageBar(),
                    "SAR Tracker",
                    f"Mission finished (elapsed {summary})",
                    duration=3
                )
            else:
                success(self.iface.messageBar(), "SAR Tracker", "Mission finished", duration=3)
            self._handle_mission_finished_cleanup()

            # CRITICAL: Refresh catalog after mission completion
            if self.layers_controller and self.layers_controller.catalog:
                try:
                    print("[SARTRACKER] Refreshing catalog after mission completion...")
                    self.layers_controller.catalog._build_cache()
                    print("[SARTRACKER] Catalog refreshed successfully")
                except Exception as e:
                    print(f"[SARTRACKER] Warning: Catalog refresh failed: {e}")

            self._refresh_mission_logs_window()

            # Show finalize button after mission ends (if not already finalized)
            if self.sar_panel and self._mission_gpkg_path:
                is_finalized = self._check_mission_finalized()
                self.sar_panel.set_finalize_button_visible(visible=True, is_finalized=is_finalized)

