        # STEP 5: Initialize UI panels
        # ====================================================================
        self._init_panels()

        # ====================================================================
        # STEP 6: Connect signals between panels and controllers
        # ====================================================================
        self._connect_signals()

        # ====================================================================
        # STEP 7: Post-initialization state setup
