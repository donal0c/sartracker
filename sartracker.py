    def _clear_provider_caches(self):
        """
        Clear provider caches and GPX import tracking for memory recovery.

        Called during mission lifecycle transitions (start/finish) to ensure
        fresh state and prevent unbounded memory growth across missions.

        MEMORY STABILITY (SAR-ezy): Provider caches persist across mission
        changes without explicit cleanup. This method clears:
        - CSV provider file cache (LRUTTLCache)
        - GPX imported files tracking set

        Safe to call at any time - handles missing components gracefully.
        """
        cleared_items = []

        # Clear CSV provider cache if available
        try:
            if self.provider and hasattr(self.provider, '_cache'):
                cache = self.provider._cache
                if hasattr(cache, 'clear'):
                    # Get stats before clearing for logging
                    stats = cache.get_stats() if hasattr(cache, 'get_stats') else {}
                    cache_size = stats.get('size', len(cache) if hasattr(cache, '__len__') else 0)

                    cache.clear()

                    # Reset statistics for fresh mission
                    if hasattr(cache, 'reset_stats'):
                        cache.reset_stats()

                    cleared_items.append(f"CSV cache ({cache_size} files)")
        except Exception as exc:
            print(f"[SARTRACKER] Warning: Failed to clear provider cache: {exc}")

        # Clear GPX imported files set
        try:
            if (self.layers_controller and
                    hasattr(self.layers_controller, 'drawings') and
                    self.layers_controller.drawings):
                drawings = self.layers_controller.drawings
                if hasattr(drawings, '_imported_gpx_files'):
                    gpx_count = len(drawings._imported_gpx_files)
                    drawings._imported_gpx_files.clear()
                    cleared_items.append(f"GPX imports ({gpx_count} files)")
        except Exception as exc:
            print(f"[SARTRACKER] Warning: Failed to clear GPX import set: {exc}")

        # Log what was cleared for debugging
        if cleared_items:
            print(f"[SARTRACKER] Mission lifecycle: cleared {', '.join(cleared_items)}")
        else:
            print("[SARTRACKER] Mission lifecycle: no caches to clear")

    def _on_finalize_mission_requested(self):
        """Handle finalize mission request from SAR Panel."""
        # CRITICAL GUARD: Check components exist (async handler may fire during unload)
        if not self.iface or not self.sar_panel or not self.layer_manager:
            print("[SARTRACKER] Finalize requested after unload, ignoring")
            return

        # Race condition protection: prevent duplicate finalization
        if self._is_finalizing:
            self._notify("info", "Finalize Mission", "Finalization already in progress, please wait.", duration=3)
            return

        if not self._mission_gpkg_path or not self._mission_directory:
            self._notify("error", "Finalize Mission", "No active mission store to finalize.", duration=5)
            return

        # Check if already finalized
        if self._check_mission_finalized():
            self._notify("info", "Finalize Mission", "Mission is already finalized.", duration=3)
            return

        self._is_finalizing = True
        try:
            # Save project before archiving
            project = QgsProject.instance()
            if project.fileName():
                if not project.write():
                    raise RuntimeError("Failed to save QGIS project before finalization")
            else:
                self._notify("error", "Finalize Mission", "Please save the project before finalizing the mission.", duration=5)
                return

            paths = self._current_mission_paths()
            project_path = Path(project.fileName()) if project.fileName() else None
            if not paths:
                raise RuntimeError("Mission storage paths are not set")

            # Run archive in background
            self._start_archive_task(paths, project_path)
            return

        except Exception as exc:
            self._notify("error", "Finalize Mission", f"Failed to finalize mission: {exc}", duration=10)
            print(f"[SARTRACKER] Error finalizing mission: {exc}")
            import traceback
            traceback.print_exc()
        finally:
            self._is_finalizing = False

    def _on_unlock_mission_requested(self):
        """Handle admin unlock request for finalized missions."""
        if not self.layer_manager or not self._check_mission_finalized():
            self._notify("info", "Mission Unlock", "Mission is not finalized.", duration=4)
            return

        admin_roster = ConfigStore.get_admin_list()
        prompt_text = "Enter admin name to unlock mission:"
        if admin_roster:
            prompt_text += f"\nAllowed: {', '.join(admin_roster)}"

        admin_name, ok = QInputDialog.getText(
            self.iface.mainWindow(),
            "Unlock Finalized Mission",
            prompt_text
        )
        if not ok:
            return
        admin_name = (admin_name or "").strip()
        if admin_roster and admin_name not in admin_roster:
            self._notify("warning", "Mission Unlock", "Admin not in roster.", duration=5)
            return

        try:
            self.layer_manager.set_mission_finalized(False, finalized_by=admin_name)
            self._notify("info", "Mission Unlock", "Mission unlocked. Editing is re-enabled.", duration=5)
            if self.sar_panel:
                self.sar_panel.set_finalize_button_visible(visible=True, is_finalized=False)
        except Exception as exc:
            self._notify("error", "Mission Unlock", f"Failed to unlock mission: {exc}", duration=6)

    def _create_mission_archive(self) -> Path:
        """
        Create a zip archive of the mission.

        Returns:
            Path to the created archive

        Raises:
            RuntimeError: If archive creation fails
        """
        import zipfile
        from datetime import datetime

        if not self._mission_directory or not self._mission_gpkg_path:
            raise RuntimeError("Mission directory or GeoPackage path not set")

        # Determine archive location (backup directory or same as mission directory)
        if self._mission_backup_directory and self._mission_backup_directory.exists():
            archive_dir = self._mission_backup_directory
        else:
            archive_dir = self._mission_directory.parent

        # Create archive filename with timestamp
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        archive_name = f"{self._mission_folder_name}_finalized_{timestamp}.zip"
        archive_path = archive_dir / archive_name

        print(f"[SARTRACKER] Creating mission archive: {archive_path}")

        try:
            with zipfile.ZipFile(archive_path, 'w', zipfile.ZIP_DEFLATED) as zipf:
                # Add GeoPackage
                if self._mission_gpkg_path.exists():
                    zipf.write(
                        self._mission_gpkg_path,
                        arcname=f"{self._mission_folder_name}/{self._mission_gpkg_path.name}"
                    )
                    print(f"[SARTRACKER] Added GeoPackage: {self._mission_gpkg_path.name}")
                else:
                    raise RuntimeError(
                        f"Mission GeoPackage not found at {self._mission_gpkg_path}. "
                        "Cannot create archive without mission data."
                    )

                # Add QGIS project file
                project = QgsProject.instance()
                project_path = Path(project.fileName())
                if project_path.exists():
                    zipf.write(
                        project_path,
                        arcname=f"{self._mission_folder_name}/{project_path.name}"
                    )
                    print(f"[SARTRACKER] Added project file: {project_path.name}")

                # Add attachments directory if it exists
                if self._mission_attachments_dir and self._mission_attachments_dir.exists():
                    for attachment_file in self._mission_attachments_dir.rglob('*'):
                        if attachment_file.is_file():
                            rel_path = attachment_file.relative_to(self._mission_directory)
                            zipf.write(
                                attachment_file,
                                arcname=f"{self._mission_folder_name}/{rel_path}"
                            )
                    print(f"[SARTRACKER] Added attachments from: {self._mission_attachments_dir}")

            print(f"[SARTRACKER] Archive created successfully: {archive_path}")
            return archive_path

        except Exception as exc:
            if archive_path.exists():
                try:
                    archive_path.unlink()
                except Exception:
                    pass
            raise RuntimeError(f"Failed to create archive: {exc}") from exc

