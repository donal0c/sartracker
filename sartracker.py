    def _sync_project_state(self, reason: str = "unknown"):
        """
        Synchronize LayerManager + mission UI with the current QGIS project.

        Life-safety: This must not mutate non-SAR projects. We only ensure the
        SAR layer structure when the project already looks like a SAR Tracker
        project (e.g., it contains SAR customVariables / root group).
        """
        if self._is_unloading or self._app_is_quitting:
            return
        if not self.layer_manager:
            return

        project = QgsProject.instance()
        try:
            project_file = project.fileName() or ""
        except Exception:
            project_file = ""

        try:
            store = self.layer_manager.get_mission_store() or ""
        except Exception:
            store = ""

        signature = f"{project_file}|{store}"
        if signature == self._last_project_signature:
            return
        self._last_project_signature = signature

        try:
            self.layer_manager.on_project_read()
        except Exception as exc:
            print(f"[SARTRACKER] Warning: LayerManager project sync failed ({reason}): {exc}")

        # Only touch the project if it already indicates a SAR mission project.
        # Never create/repair structure on an unsaved startup "Untitled Project"
        # unless a mission store is already configured. This avoids dirtying the
        # transient startup project and triggering QGIS' save prompt.
        should_ensure = False
        try:
            is_sar = bool(self.layer_manager.is_sar_project())
            should_ensure = bool(store) or (bool(project_file) and is_sar)
        except Exception:
            should_ensure = False

        if should_ensure:
            try:
                self.layer_manager.ensure_structure(auto_migrate=True)
            except Exception as exc:
                self._log_exception(f"_sync_project_state.ensure_structure.{reason}", exc)
                warning(
                    self.iface.messageBar(),
                    "Layer Structure",
                    f"Could not verify SAR layer structure for this project: {exc}",
                    duration=6,
                )
            # Optional: helicopter placeholder layers are initialized lazily to
            # avoid dirtying the startup "Untitled Project" during plugin load.
            try:
                if self.layers_controller:
                    self.layers_controller.ensure_helicopter_layers()
            except Exception as exc:
                print(f"[SARTRACKER] Warning: Helicopter layer init failed: {exc}")

        # Refresh mission storage UI + resume prompt logic now that project vars are stable.
        try:
            if self.sar_panel:
                self._load_existing_mission_storage_state()
        except Exception as exc:
            self._log_exception(f"_sync_project_state.load_existing.{reason}", exc)

    def _load_existing_mission_storage_state(self):
        """Initialize mission storage label based on current LayerManager state."""
        if not self.layer_manager:
            return

        store_path = self.layer_manager.get_mission_store()
        if not store_path:
            self._mission_gpkg_path = None
            self._mission_directory = None
            self._mission_folder_name = None
            self._mission_backup_directory = None
            self._mission_attachments_dir = None
            self._update_mission_storage_status(active=False)
            return

        # Show resume prompt if mission store exists
        gpkg_path = Path(store_path)
        if gpkg_path.exists():
            try:
                should_resume = self._show_resume_mission_prompt(gpkg_path)
            except Exception as prompt_error:
                print(f"[SARTRACKER] ERROR in resume prompt: {prompt_error}")
                import traceback
                traceback.print_exc()

                error(
                    self.iface.messageBar(),
                    "Mission Resume",
                    f"Failed to show resume dialog. Starting fresh.",
                    duration=5
                )

                # Safe fallback: start fresh
                should_resume = False

            if not should_resume:
                # User chose "Start Fresh" - immediately create/attach a new empty mission store
                mission_name = self._prompt_new_mission_name()
                if not mission_name:
                    info(
                        self.iface.messageBar(),
                        "SAR Tracker",
                        "Start Fresh cancelled; continuing with existing mission store.",
                        duration=4
                    )
                    return

                self._prepare_new_mission_storage(mission_name)
                try:
                    if self.mission_controller:
                        self.mission_controller.clear_saved_state()
                except Exception as exc:
                    print(f"[SARTRACKER] Warning: Failed to clear saved mission state: {exc}")
                # Reflect idle state in UI badges if mission controller not active yet
                is_active = self.mission_controller.is_active() if self.mission_controller else False
                self._update_mission_storage_status(active=is_active)
                info(
                    self.iface.messageBar(),
                    "SAR Tracker",
                    f"New mission storage created for '{mission_name}'.",
                    duration=4
                )
                # Show finalize button if idle and layers exist (consistent with resume path)
                if self.sar_panel and not is_active:
                    is_finalized = self._check_mission_finalized()
                    self.sar_panel.set_finalize_button_visible(visible=True, is_finalized=is_finalized)
                return

        # User chose resume or no prompt needed - continue loading
        self._mission_gpkg_path = gpkg_path
        self._mission_directory = gpkg_path.parent
        self._mission_folder_name = self._mission_directory.name
        attachments_dir = self._mission_directory / "attachments"
        try:
            if attachments_dir.exists():
                self._mission_attachments_dir = attachments_dir
            else:
                attachments_dir.mkdir(parents=True, exist_ok=True)
                self._mission_attachments_dir = attachments_dir
        except Exception as exc:
            self._mission_attachments_dir = None
            self._log_exception("_load_existing_mission_storage_state.attachments", exc)
            warning(
                self.iface.messageBar(),
                "Mission Storage",
                "Attachments folder could not be prepared. Attachments will stay at original paths.",
                duration=6
            )

        self._mission_backup_directory = None
