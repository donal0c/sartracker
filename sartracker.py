    def _on_autosave_requested(self):
        """Handle auto-save request from SAR Panel."""
        try:
            # Save the current QGIS project
            project = QgsProject.instance()

            persistence_ok = True
            backup_ok = True

            # Check if project has a file path
            if project.fileName():
                # Project already has a file, save it
                save_success = project.write()

                if save_success:
                    persistence_issues = self.layer_manager.validate_persistence(quiet=True) if self.layer_manager else {}
                    persistence_ok = not persistence_issues
                    backup_ok = self._sync_mission_backup(async_run=True)
                    if not persistence_ok:
                        warning(
                            self.iface.messageBar(),
                            "Persistence",
                            f"{len(persistence_issues)} layer(s) still in memory during auto-save.",
                            duration=4
                        )
                    if not backup_ok:
                        warning(
                            self.iface.messageBar(),
                            "Mission Backup",
                            "Mission backup could not be completed.",
                            duration=4
                        )
                    overall_success = persistence_ok and backup_ok
                    self.sar_panel.update_autosave_status(overall_success)
                    if overall_success:
                        success(
                            self.iface.messageBar(),
                            "SAR Tracker",
                            "Project saved successfully",
                            duration=2
                        )
                else:
                    self.sar_panel.update_autosave_status(False)
                    error(
                        self.iface.messageBar(),
                        "SAR Tracker",
                        "Failed to save project",
                        duration=3
                    )
            else:
                # Project hasn't been saved yet - prompt for location
                file_path, _ = QFileDialog.getSaveFileName(
                    self.iface.mainWindow(),
                    "Save QGIS Project",
                    "",
                    "QGIS Project Files (*.qgz *.qgs)"
                )

                if file_path:
                    save_success = project.write(file_path)

                    if save_success:
                        persistence_issues = self.layer_manager.validate_persistence(quiet=True) if self.layer_manager else {}
                        persistence_ok = not persistence_issues
                        backup_ok = self._sync_mission_backup(async_run=True)
                        overall_success = persistence_ok and backup_ok
                        if not persistence_ok:
                            warning(
                                self.iface.messageBar(),
                                "Persistence",
                                f"{len(persistence_issues)} layer(s) still in memory during auto-save.",
                                duration=4
                            )
                        if not backup_ok:
                            warning(
                                self.iface.messageBar(),
                                "Mission Backup",
                                "Mission backup could not be completed.",
                                duration=4
                            )
                        self.sar_panel.update_autosave_status(overall_success)
                        if overall_success:
                            success(
                                self.iface.messageBar(),
                                "SAR Tracker",
                                f"Project saved to {file_path}",
                                duration=3
                            )
                    else:
                        self.sar_panel.update_autosave_status(False)
                else:
                    # User cancelled - don't mark as failed
                    pass

        except Exception as e:
            if self.sar_panel:
                self.sar_panel.update_autosave_status(False)
            self._log_exception("_on_autosave_requested", e)
            QMessageBox.critical(
                self.iface.mainWindow(),
                "Auto-Save Error",
                f"Error saving project:\n\n{str(e)}"
            )

