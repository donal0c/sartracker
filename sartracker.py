    def _notify(self, level: str, title: str, message: str, duration: int = 3):
        """
        Centralized notifier wrapper to simplify messaging and future redirection.

        LIFECYCLE SAFETY: Guards against notifications during plugin unload/shutdown.
        """
        # LIFECYCLE SAFETY: Suppress notifications during unload
        if getattr(self, '_is_unloading', False) or getattr(self, '_app_is_quitting', False):
            print(f"[SARTRACKER] Notification suppressed during unload ({level}): {title}")
            return

        # LIFECYCLE SAFETY: Guard messageBar() access - can raise RuntimeError
        # if underlying C++ object is deleted during QGIS shutdown
        try:
            bar = self.iface.messageBar() if self.iface else None
        except (RuntimeError, AttributeError):
            print(f"[SARTRACKER] Notification suppressed (messageBar unavailable): {title}")
            return

        try:
            if level == "info":
                info(bar, title, message, duration=duration)
            elif level == "warning":
                warning(bar, title, message, duration=duration)
            elif level == "error":
                error(bar, title, message, duration=duration)
            elif level == "success":
                success(bar, title, message, duration=duration)
        except Exception as e:
            print(f"[SARTRACKER] Notify failed ({level}): {e}")

    def _log_exception(self, context: str, exc: Exception):
        """Log an exception with context and traceback for diagnostics."""
        try:
            tb = traceback.format_exc()
        except Exception:
            tb = None
        print(f"[SARTRACKER][{context}] {exc}")
        if tb:
            print(tb)

    def _is_number(self, value) -> bool:
        """Return True if value can be interpreted as a finite float (excludes bool)."""
        if value is None or isinstance(value, bool):
            return False
        try:
            return math.isfinite(float(value))
        except Exception:
            return False

    def _valid_latlon(self, lat, lon) -> bool:
        """Basic latitude/longitude validation."""
        if not self._is_number(lat) or not self._is_number(lon):
            return False
        lat_f = float(lat)
        lon_f = float(lon)
        return -90.0 <= lat_f <= 90.0 and -180.0 <= lon_f <= 180.0

